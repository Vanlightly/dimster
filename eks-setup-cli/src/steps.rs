/// When true, skip all interactive confirmations.
static AUTO_ACCEPT: AtomicBool = AtomicBool::new(false);

pub fn set_auto_accept(value: bool) {
    AUTO_ACCEPT.store(value, Ordering::Relaxed);
}

use crate::answers::Answers;

#[derive(Clone, Copy, PartialEq)]
pub enum Mode {
    Execute,
    DryRun,
    GenerateScript,
}

/// Script builder — collects lines for --generate-script mode.
struct Script {
    lines: Vec<String>,
}

impl Script {
    fn new() -> Self {
        Self { lines: Vec::new() }
    }

    fn comment(&mut self, text: &str) {
        self.lines.push(format!("# {}", text));
    }

    fn blank(&mut self) {
        self.lines.push(String::new());
    }

    fn section(&mut self, title: &str) {
        self.blank();
        self.lines.push(format!("# {}", "=".repeat(60)));
        self.lines.push(format!("# {}", title));
        self.lines.push(format!("# {}", "=".repeat(60)));
        self.blank();
    }

    fn cmd(&mut self, command: &str) {
        self.lines.push(command.to_string());
    }

    fn heredoc(&mut self, command: &str, content: &str) {
        self.lines.push(format!("{} <<'EOF'", command));
        for line in content.lines() {
            self.lines.push(line.to_string());
        }
        self.lines.push("EOF".to_string());
    }

    fn render(&self) -> String {
        self.lines.join("\n")
    }
}

pub fn run_all(answers: &Answers, mode: Mode) -> Result<()> {
    if mode == Mode::GenerateScript {
        let script = generate_script(answers)?;
        print!("{}", script);
        return Ok(());
    }

    step_1_ecr(answers, mode)?;
    step_2_eks(answers, mode)?;

    // Always install EBS CSI driver — even with instance-store Kafka,
    // the coordinator needs EBS for its results PVC
    step_3_ebs_csi(answers, mode)?;

    if answers.is_external() {
        println!("\n=== Step 4/5: Create StorageClass — skipped (external) ===\n");
    } else {
        step_4_storage(answers, mode)?;
    }
    let inserted = step_5_generate(answers, mode)?;

    println!("\n=== Done! ===\n");
    let name = &answers.aws.dimster_name;
    let region = &answers.aws.region;
    let env_name = &answers.env_name;

    // Get account ID for the docker login command
    let account_id = Command::new("aws")
        .args(["sts", "get-caller-identity", "--query", "Account", "--output", "text"])
        .output()
        .ok()
        .map(|o| String::from_utf8_lossy(&o.stdout).trim().to_string())
        .unwrap_or_else(|| "<ACCOUNT_ID>".to_string());

    println!("  Next steps:");
    let mut step = 1;
    if inserted {
        println!("    ✓ Config updated in dimster-config.yaml");
    } else {
        println!("    {}. Review dimster-config-{}.yaml", step, name);
        step += 1;
        println!("    {}. Copy: cp dimster-config-{}.yaml dimster-config.yaml", step, name);
        step += 1;
    }
    println!("    {}. Log in to ECR (token expires every 12 hours):", step);
    println!("       aws ecr get-login-password --region {} | \\", region);
    println!("         docker login --username AWS --password-stdin {}.dkr.ecr.{}.amazonaws.com", account_id, region);
    step += 1;
    println!("    {}. Build and push: ./dimster build {}", step, env_name);
    step += 1;
    println!("    {}. Deploy: ./dimster deploy {}", step, env_name);

    Ok(())
}

