/// Check which node groups exist and create any that are missing.
fn ensure_node_groups(answers: &Answers, cluster_name: &str, config_path: &str, eksctl_config: &str) -> Result<()> {
    let output = Command::new("eksctl")
        .args(["get", "nodegroup", "--cluster", cluster_name, "--region", &answers.aws.region, "-o", "json"])
        .output()?;

    if !output.status.success() {
        let stderr = String::from_utf8_lossy(&output.stderr);
        bail!("Failed to list node groups: {}", stderr);
    }

    let json_str = String::from_utf8_lossy(&output.stdout);
    let nodegroups: serde_json::Value = serde_json::from_str(&json_str)
        .unwrap_or_else(|_| serde_json::Value::Array(vec![]));

    let existing: Vec<String> = nodegroups.as_array()
        .unwrap_or(&vec![])
        .iter()
        .filter_map(|ng| ng.get("Name").and_then(|n| n.as_str()).map(|s| s.to_string()))
        .collect();

    // Determine which node groups are expected
    let mut expected = vec!["workers", "infra"];
    if !answers.is_external() {
        expected.push("kafka");
    }

    let missing: Vec<&&str> = expected.iter().filter(|name| !existing.contains(&name.to_string())).collect();

    if missing.is_empty() {
        println!("  ✓ All required node groups present: {}", existing.join(", "));
        return Ok(());
    }

    println!("  Existing node groups: {}", existing.join(", "));
    println!("  Missing node groups: {}", missing.iter().map(|s| **s).collect::<Vec<_>>().join(", "));

    // Write the full eksctl config and use it to create only the missing node groups
    std::fs::write(config_path, eksctl_config)?;

    for ng in &missing {
        println!("\n  Creating node group '{}'...", ng);
        confirm_and_run_inherit(
            "eksctl",
            &["create", "nodegroup", "--config-file", config_path, "--include", ng],
        )?;
        println!("  ✓ Node group '{}' created", ng);
    }

    Ok(())
}

fn step_3_ebs_csi(answers: &Answers, mode: Mode) -> Result<()> {
    println!("\n=== Step 3/5: Install EBS CSI Driver ===\n");

    let cluster_name = format!("{}-benchmark", answers.aws.dimster_name);
    let region = &answers.aws.region;

    if mode == Mode::DryRun {
        println!("  [dry-run] eksctl utils associate-iam-oidc-provider --cluster {} --region {} --approve", cluster_name, region);
        println!("  [dry-run] eksctl create iamserviceaccount --cluster {} --name ebs-csi-controller-sa --namespace kube-system ...", cluster_name);
        println!("  [dry-run] eksctl create addon --cluster {} --name aws-ebs-csi-driver ...", cluster_name);
        return Ok(());
    }

    // Check if already installed
    let check = Command::new("kubectl")
        .args(["get", "pods", "-n", "kube-system", "-l", "app.kubernetes.io/name=aws-ebs-csi-driver", "--no-headers"])
        .output()?;

    if check.status.success() && !String::from_utf8_lossy(&check.stdout).trim().is_empty() {
        println!("  ✓ EBS CSI driver already installed");
        mark_default_storage_class()?;
        return Ok(());
    }

    // 1. OIDC provider
    confirm_and_run_inherit(
        "eksctl",
        &["utils", "associate-iam-oidc-provider", "--region", region, "--cluster", &cluster_name, "--approve"],
    )?;

    // 2. IAM service account
    confirm_and_run_inherit(
        "eksctl",
        &[
            "create", "iamserviceaccount",
            "--cluster", &cluster_name,
            "--region", region,
            "--name", "ebs-csi-controller-sa",
            "--namespace", "kube-system",
            "--attach-policy-arn", "arn:aws:iam::aws:policy/service-role/AmazonEBSCSIDriverPolicy",
            "--approve",
            "--override-existing-serviceaccounts",
        ],
    )?;

    // 3. Get role ARN
    let arn_output = Command::new("kubectl")
        .args([
            "get", "sa", "ebs-csi-controller-sa", "-n", "kube-system",
            "-o", "jsonpath={.metadata.annotations.eks\\.amazonaws\\.com/role-arn}",
        ])
        .output()?;

    let role_arn = String::from_utf8_lossy(&arn_output.stdout).trim().to_string();
    if role_arn.is_empty() {
        bail!("Could not get EBS CSI role ARN");
    }
    println!("  Role ARN: {}", role_arn);

    // 4. Install addon
    confirm_and_run_inherit(
        "eksctl",
        &[
            "create", "addon",
            "--cluster", &cluster_name,
            "--region", region,
            "--name", "aws-ebs-csi-driver",
            "--service-account-role-arn", &role_arn,
            "--force",
        ],
    )?;

    println!("  ✓ EBS CSI driver installed");

    // Mark gp2 as default StorageClass (eksctl creates it without the annotation)
    mark_default_storage_class()?;

    Ok(())
}

fn mark_default_storage_class() -> Result<()> {
    // Check if any StorageClass is already marked as default
    let output = Command::new("kubectl")
        .args(["get", "sc", "-o", "jsonpath={.items[?(@.metadata.annotations.storageclass\\.kubernetes\\.io/is-default-class==\"true\")].metadata.name}"])
        .output()?;

    let defaults = String::from_utf8_lossy(&output.stdout).trim().to_string();
    if !defaults.is_empty() {
        println!("  ✓ Default StorageClass already set: {}", defaults);
        return Ok(());
    }

    // Mark gp2 as default (created by eksctl)
    let status = Command::new("kubectl")
        .args(["annotate", "storageclass", "gp2", "storageclass.kubernetes.io/is-default-class=true", "--overwrite"])
        .stdout(std::process::Stdio::inherit())
        .stderr(std::process::Stdio::inherit())
        .status()?;

    if status.success() {
        println!("  ✓ Marked gp2 as default StorageClass");
    } else {
        println!("  ⚠ Could not mark gp2 as default StorageClass — coordinator PVC may not bind");
    }
    Ok(())
}

