/// Print the command, ask for confirmation, then run it (capturing output).
fn confirm_and_run(program: &str, args: &[&str]) -> Result<()> {
    println!("  → {} {}", program, args.join(" "));

    if !AUTO_ACCEPT.load(Ordering::Relaxed) {
        let proceed = Confirm::new()
            .with_prompt("  Run this command?")
            .default(true)
            .interact()?;

        if !proceed {
            bail!("Aborted by user");
        }
    }

    let output = Command::new(program).args(args).output()?;
    if !output.status.success() {
        let stderr = String::from_utf8_lossy(&output.stderr);
        bail!("{} failed: {}", program, stderr);
    }
    Ok(())
}

/// Print the command, ask for confirmation, then run it (inheriting stdio).
fn confirm_and_run_inherit(program: &str, args: &[&str]) -> Result<()> {
    println!("  → {} {}", program, args.join(" "));

    if !AUTO_ACCEPT.load(Ordering::Relaxed) {
        let proceed = Confirm::new()
            .with_prompt("  Run this command?")
            .default(true)
            .interact()?;

        if !proceed {
            bail!("Aborted by user");
        }
    }

    let status = Command::new(program)
        .args(args)
        .stdin(std::process::Stdio::inherit())
        .stdout(std::process::Stdio::inherit())
        .stderr(std::process::Stdio::inherit())
        .status()?;

    if !status.success() {
        bail!("{} {} failed", program, args.first().unwrap_or(&""));
    }
    Ok(())
}

/// Print a description, ask for confirmation, then pipe manifest to kubectl apply.
fn confirm_and_apply(description: &str, manifest: &str) -> Result<()> {
    println!("  → kubectl apply: {}", description);

    if !AUTO_ACCEPT.load(Ordering::Relaxed) {
        let proceed = Confirm::new()
            .with_prompt("  Apply this manifest?")
            .default(true)
            .interact()?;

        if !proceed {
            bail!("Aborted by user");
        }
    }

    let mut child = Command::new("kubectl")
        .args(["apply", "-f", "-"])
        .stdin(std::process::Stdio::piped())
        .stdout(std::process::Stdio::inherit())
        .stderr(std::process::Stdio::inherit())
        .spawn()?;

    if let Some(mut stdin) = child.stdin.take() {
        stdin.write_all(manifest.as_bytes())?;
    }

    let status = child.wait()?;
    if !status.success() {
        bail!("kubectl apply failed");
    }
    Ok(())
}

/// Shell script for the NVMe format DaemonSet container.
/// Discovers all NVMe instance-store devices, uses RAID 0 if multiple.
fn nvme_setup_script() -> &'static str {
    // Each line is indented 14 spaces to align under the YAML `- |` block
    "              MOUNT=/mnt/nvme0
              if mountpoint -q \"$MOUNT\"; then
                echo \"$MOUNT already mounted\"
                sleep infinity
              fi
              yum install -y xfsprogs mdadm > /dev/null 2>&1
              # Find all NVMe instance-store devices (exclude root EBS nvme0n1)
              DEVICES=()
              for dev in /dev/nvme*n1; do
                [ -b \"$dev\" ] || continue
                [ \"$dev\" = \"/dev/nvme0n1\" ] && continue
                DEVICES+=(\"$dev\")
              done
              if [ ${#DEVICES[@]} -eq 0 ]; then
                echo \"No NVMe instance-store devices found\"
                sleep infinity
              fi
              echo \"Found ${#DEVICES[@]} NVMe device(s): ${DEVICES[*]}\"
              if [ ${#DEVICES[@]} -eq 1 ]; then
                DEVICE=${DEVICES[0]}
                echo \"Single device, formatting $DEVICE as xfs...\"
                mkfs.xfs -f \"$DEVICE\"
                mkdir -p \"$MOUNT\"
                mount \"$DEVICE\" \"$MOUNT\"
              else
                echo \"Multiple devices, creating RAID 0...\"
                mdadm --create /dev/md0 --level=0 --raid-devices=${#DEVICES[@]} ${DEVICES[*]} --force
                echo \"Formatting /dev/md0 as xfs...\"
                mkfs.xfs -f /dev/md0
                mkdir -p \"$MOUNT\"
                mount /dev/md0 \"$MOUNT\"
              fi
              chmod 777 \"$MOUNT\"
              echo \"$MOUNT mounted successfully\"
              sleep infinity"
}
