fn setup_ebs_storage(answers: &Answers, mode: Mode) -> Result<()> {
    let is_provisioned = answers.storage.performance.as_deref() == Some("provisioned");
    let dimster_name = &answers.aws.dimster_name;
    let cluster_name = format!("{}-benchmark", dimster_name);

    // Tag every dynamically-provisioned EBS volume with the cluster + dimster
    // name so teardown can safely identify and sweep orphans without risking
    // unrelated volumes in the same AWS account.
    let tag_params = format!(
        "  tagSpecification_1: \"dimster-cluster={}\"\n  tagSpecification_2: \"dimster-name={}\"",
        cluster_name, dimster_name
    );

    let (sc_name, params) = if is_provisioned {
        let iops = answers.storage.iops.unwrap_or(16000);
        let throughput = answers.storage.throughput_mbs.unwrap_or(1000);
        (
            "gp3-fast",
            format!("  type: gp3\n  fsType: xfs\n  iops: \"{}\"\n  throughput: \"{}\"\n{}", iops, throughput, tag_params),
        )
    } else {
        ("gp3", format!("  type: gp3\n  fsType: xfs\n{}", tag_params))
    };

    // Explicit reclaimPolicy: Delete — already the default for dynamic
    // provisioning, but stating it makes intent unambiguous.
    let manifest = format!(
        "apiVersion: storage.k8s.io/v1\nkind: StorageClass\nmetadata:\n  name: {sc_name}\nprovisioner: ebs.csi.aws.com\nparameters:\n{params}\nreclaimPolicy: Delete\nvolumeBindingMode: WaitForFirstConsumer\nallowVolumeExpansion: true\n",
    );

    if mode == Mode::DryRun {
        println!("  [dry-run] kubectl apply StorageClass '{}':", sc_name);
        for line in manifest.lines() {
            println!("    {}", line);
        }
        return Ok(());
    }

    confirm_and_apply("Create StorageClass", &manifest)?;
    println!("  ✓ StorageClass '{}' created", sc_name);
    Ok(())
}

fn setup_instance_store(answers: &Answers, mode: Mode) -> Result<()> {
    let sc_manifest = "apiVersion: storage.k8s.io/v1\nkind: StorageClass\nmetadata:\n  name: local-storage\nprovisioner: kubernetes.io/no-provisioner\nvolumeBindingMode: WaitForFirstConsumer\n";

    let daemonset_manifest = format!(r#"apiVersion: apps/v1
kind: DaemonSet
metadata:
  name: nvme-format
  namespace: kube-system
spec:
  selector:
    matchLabels:
      app: nvme-format
  template:
    metadata:
      labels:
        app: nvme-format
    spec:
      nodeSelector:
        role: kafka
      containers:
        - name: format
          image: amazonlinux:2023
          securityContext:
            privileged: true
          command:
            - /bin/bash
            - -c
            - |
{NVME_SETUP_SCRIPT}
          volumeMounts:
            - name: dev
              mountPath: /dev
            - name: mnt
              mountPath: /mnt
              mountPropagation: Bidirectional
      volumes:
        - name: dev
          hostPath:
            path: /dev
        - name: mnt
          hostPath:
            path: /mnt
      tolerations:
        - operator: Exists
"#, NVME_SETUP_SCRIPT = nvme_setup_script());

    if mode == Mode::DryRun {
        println!("  [dry-run] kubectl apply StorageClass 'local-storage'");
        println!("  [dry-run] kubectl apply DaemonSet 'nvme-format' (formats NVMe on kafka nodes)");
        println!("  [dry-run] kubectl get nodes -l role=kafka → create PVs");
        println!("  PV capacity: {}", answers.storage.size);
        return Ok(());
    }

    // Apply StorageClass
    confirm_and_apply("Create local-storage StorageClass", sc_manifest)?;

    // Apply DaemonSet
    confirm_and_apply("Deploy NVMe format DaemonSet", &daemonset_manifest)?;

    // Wait for DaemonSet
    println!("  Waiting for NVMe format to complete on all kafka nodes...");
    let _ = Command::new("kubectl")
        .args(["rollout", "status", "daemonset/nvme-format", "-n", "kube-system", "--timeout=120s"])
        .stdin(std::process::Stdio::inherit())
        .stdout(std::process::Stdio::inherit())
        .stderr(std::process::Stdio::inherit())
        .status();

    // Get kafka node names
    let output = Command::new("kubectl")
        .args(["get", "nodes", "-l", "role=kafka", "-o", "jsonpath={.items[*].metadata.name}"])
        .output()?;

    let nodes_str = String::from_utf8_lossy(&output.stdout).trim().to_string();
    if nodes_str.is_empty() {
        bail!("No nodes found with label role=kafka");
    }

    let nodes: Vec<&str> = nodes_str.split_whitespace().collect();
    println!("  Found {} kafka node(s): {}", nodes.len(), nodes.join(", "));

    // Create PVs
    for (i, node) in nodes.iter().enumerate() {
        let pv_manifest = format!(
            "apiVersion: v1\nkind: PersistentVolume\nmetadata:\n  name: kafka-nvme-{i}\nspec:\n  capacity:\n    storage: {size}\n  accessModes: [\"ReadWriteOnce\"]\n  persistentVolumeReclaimPolicy: Delete\n  storageClassName: local-storage\n  local:\n    path: /mnt/nvme0\n  nodeAffinity:\n    required:\n      nodeSelectorTerms:\n        - matchExpressions:\n            - key: kubernetes.io/hostname\n              operator: In\n              values: [\"{node}\"]\n",
            i = i, size = answers.storage.size, node = node,
        );
        confirm_and_apply(&format!("Create PV kafka-nvme-{} on {}", i, node), &pv_manifest)?;
    }

    println!("  ✓ Local storage configured ({} PVs)", nodes.len());
    println!("  ℹ NVMe format DaemonSet left running to maintain mount propagation");

    Ok(())
}

