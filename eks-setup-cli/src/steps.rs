fn generate_script(answers: &Answers) -> Result<String> {
    let mut s = Script::new();
    let name = &answers.aws.dimster_name;
    let region = &answers.aws.region;
    let cluster_name = format!("{}-benchmark", name);

    s.cmd("#!/usr/bin/env bash");
    s.cmd("set -euo pipefail");
    s.blank();
    s.comment(&format!("EKS setup script for '{}'", name));
    s.comment("Generated by eks-setup. Review and edit before running.");

    // Variables
    s.section("Variables");
    s.cmd(&format!("DIMSTER_NAME=\"{}\"", name));
    s.cmd(&format!("AWS_REGION=\"{}\"", region));
    s.cmd(&format!("AWS_AZ=\"{}\"", answers.aws.az));
    // Second AZ for VPC subnets (eksctl needs at least 2); node groups still pinned to AWS_AZ
    let second_az_script = {
        let suffix = answers.aws.az.chars().last().unwrap_or('a');
        let other = if suffix == 'a' { 'b' } else { 'a' };
        format!("{}{}", &answers.aws.az[..answers.aws.az.len() - 1], other)
    };
    s.cmd(&format!("SECOND_AZ=\"{}\"", second_az_script));
    s.cmd(&format!("CLUSTER_NAME=\"{}\"", cluster_name));
    s.cmd("AWS_ACCOUNT_ID=$(aws sts get-caller-identity --query Account --output text)");

    // Step 1: ECR
    s.section("Step 1: Create ECR Repository");
    s.comment("Check if repository already exists");
    s.cmd(&format!(
        "if ! aws ecr describe-repositories --repository-names \"$DIMSTER_NAME\" --region \"$AWS_REGION\" &>/dev/null; then"
    ));
    s.cmd(&format!(
        "  aws ecr create-repository --repository-name \"$DIMSTER_NAME\" --region \"$AWS_REGION\""
    ));
    s.cmd("  echo \"ECR repository created\"");
    s.cmd("else");
    s.cmd("  echo \"ECR repository already exists\"");
    s.cmd("fi");

    // Step 2: EKS cluster
    s.section("Step 2: Create EKS Cluster");

    let script_kafka_node_group = if answers.is_external() {
        String::new()
    } else {
        format!(
            r#"  - name: kafka
    instanceType: {kafka_type}
    desiredCapacity: {kafka_count}
    minSize: {kafka_count}
    maxSize: {kafka_count}
    availabilityZones: ["${{AWS_AZ}}"]
    labels:
      role: kafka

"#,
            kafka_type = answers.kafka.instance_type,
            kafka_count = answers.kafka.count,
        )
    };

    let eksctl_config = format!(
        r#"apiVersion: eksctl.io/v1alpha5
kind: ClusterConfig

metadata:
  name: ${{CLUSTER_NAME}}
  region: ${{AWS_REGION}}
  version: "{eks_version}"

availabilityZones: ["${{AWS_AZ}}", "${{SECOND_AZ}}"]

managedNodeGroups:
{kafka_node_group}  - name: workers
    instanceType: {worker_type}
    desiredCapacity: {worker_count}
    minSize: {worker_min}
    maxSize: {worker_max}
    availabilityZones: ["${{AWS_AZ}}"]
    labels:
      role: worker

  - name: infra
    instanceType: {infra_type}
    desiredCapacity: 1
    minSize: 1
    maxSize: 1
    availabilityZones: ["${{AWS_AZ}}"]
    labels:
      role: infra"#,
        eks_version = answers.aws.eks_version,
        kafka_node_group = script_kafka_node_group,
        worker_type = answers.workers.instance_type,
        worker_count = answers.workers.count,
        worker_min = answers.workers.min,
        worker_max = answers.workers.max,
        infra_type = answers.coordinator.infra_instance_type,
    );

    let eksctl_path = format!("/tmp/eks-cluster-{}.yaml", name);
    s.comment("Check if cluster already exists");
    s.cmd(&format!(
        "if ! eksctl get cluster --name \"$CLUSTER_NAME\" --region \"$AWS_REGION\" &>/dev/null; then"
    ));
    s.cmd(&format!("  cat > {} <<'EKSCTL_EOF'", eksctl_path));
    for line in eksctl_config.lines() {
        s.cmd(&format!("  {}", line));
    }
    s.cmd("EKSCTL_EOF");
    s.blank();
    s.cmd(&format!("  echo \"Creating EKS cluster (this takes 15-20 minutes)...\""));
    s.cmd(&format!("  eksctl create cluster -f {}", eksctl_path));
    s.cmd("  echo \"EKS cluster created\"");
    s.cmd("else");
    s.cmd("  echo \"EKS cluster already exists\"");
    s.cmd("fi");
    s.blank();
    s.comment("Verify nodes");
    s.cmd("kubectl get nodes -o custom-columns=NAME:.metadata.name,ZONE:.metadata.labels.topology\\.kubernetes\\.io/zone,ROLE:.metadata.labels.role");

    // Step 3: EBS CSI driver — always needed (coordinator uses EBS even with instance-store Kafka)
    {
        s.section("Step 3: Install EBS CSI Driver");

        s.comment("Check if already installed");
        s.cmd("if ! kubectl get pods -n kube-system -l app.kubernetes.io/name=aws-ebs-csi-driver --no-headers 2>/dev/null | grep -q .; then");
        s.blank();
        s.cmd("  # Associate OIDC provider");
        s.cmd(&format!(
            "  eksctl utils associate-iam-oidc-provider \\\n    --region \"$AWS_REGION\" \\\n    --cluster \"$CLUSTER_NAME\" \\\n    --approve"
        ));
        s.blank();
        s.cmd("  # Create IAM service account");
        s.cmd(&format!(
            "  eksctl create iamserviceaccount \\\n    --cluster \"$CLUSTER_NAME\" \\\n    --region \"$AWS_REGION\" \\\n    --name ebs-csi-controller-sa \\\n    --namespace kube-system \\\n    --attach-policy-arn arn:aws:iam::aws:policy/service-role/AmazonEBSCSIDriverPolicy \\\n    --approve \\\n    --override-existing-serviceaccounts"
        ));
        s.blank();
        s.cmd("  # Get role ARN");
        s.cmd("  EBS_CSI_ROLE_ARN=$(kubectl get sa ebs-csi-controller-sa -n kube-system \\\n    -o jsonpath='{.metadata.annotations.eks\\.amazonaws\\.com/role-arn}')");
        s.cmd("  echo \"Role ARN: $EBS_CSI_ROLE_ARN\"");
        s.blank();
        s.cmd("  # Install the addon");
        s.cmd(&format!(
            "  eksctl create addon \\\n    --cluster \"$CLUSTER_NAME\" \\\n    --region \"$AWS_REGION\" \\\n    --name aws-ebs-csi-driver \\\n    --service-account-role-arn \"$EBS_CSI_ROLE_ARN\" \\\n    --force"
        ));
        s.cmd("  echo \"EBS CSI driver installed\"");
        s.blank();
        s.cmd("else");
        s.cmd("  echo \"EBS CSI driver already installed\"");
        s.cmd("fi");
        s.blank();

        s.comment("Mark gp2 as default StorageClass if no default exists");
        s.cmd("if ! kubectl get sc -o jsonpath='{.items[?(@.metadata.annotations.storageclass\\.kubernetes\\.io/is-default-class==\"true\")].metadata.name}' | grep -q .; then");
        s.cmd("  kubectl annotate storageclass gp2 storageclass.kubernetes.io/is-default-class=true --overwrite");
        s.cmd("  echo \"Marked gp2 as default StorageClass\"");
        s.cmd("else");
        s.cmd("  echo \"Default StorageClass already set\"");
        s.cmd("fi");
    }

    // Step 4: StorageClass
    s.section("Step 4: Create StorageClass");

    if answers.is_external() {
        s.comment("Skipped — external mode (no Kafka storage needed)");
        s.cmd("echo \"Step 4 skipped (external mode)\"");
    } else if answers.storage.storage_type == "instance-store" {
        // Local storage class
        let sc = "apiVersion: storage.k8s.io/v1\nkind: StorageClass\nmetadata:\n  name: local-storage\nprovisioner: kubernetes.io/no-provisioner\nvolumeBindingMode: WaitForFirstConsumer";
        s.heredoc("kubectl apply -f -", sc);
        s.blank();

        // NVMe format DaemonSet
        s.comment("Format and mount NVMe drives on kafka nodes");
        let ds = format!(r#"apiVersion: apps/v1
kind: DaemonSet
metadata:
  name: nvme-format
  namespace: kube-system
spec:
  selector:
    matchLabels:
      app: nvme-format
  template:
    metadata:
      labels:
        app: nvme-format
    spec:
      nodeSelector:
        role: kafka
      containers:
        - name: format
          image: amazonlinux:2023
          securityContext:
            privileged: true
          command:
            - /bin/bash
            - -c
            - |
{NVME_SETUP_SCRIPT}
          volumeMounts:
            - name: dev
              mountPath: /dev
            - name: mnt
              mountPath: /mnt
              mountPropagation: Bidirectional
      volumes:
        - name: dev
          hostPath:
            path: /dev
        - name: mnt
          hostPath:
            path: /mnt
      tolerations:
        - operator: Exists"#, NVME_SETUP_SCRIPT = nvme_setup_script());
        s.heredoc("kubectl apply -f -", &ds);
        s.blank();
        s.cmd("echo \"Waiting for NVMe format to complete...\"");
        s.cmd("kubectl rollout status daemonset/nvme-format -n kube-system --timeout=120s || true");
        s.blank();

        // Create PVs
        s.comment("Create a PersistentVolume for each kafka node");
        s.cmd("KAFKA_NODES=$(kubectl get nodes -l role=kafka -o jsonpath='{.items[*].metadata.name}')");
        s.cmd("INDEX=0");
        s.cmd("for NODE in $KAFKA_NODES; do");
        s.cmd(&format!(r#"  kubectl apply -f - <<PV_EOF
apiVersion: v1
kind: PersistentVolume
metadata:
  name: kafka-nvme-$INDEX
spec:
  capacity:
    storage: {size}
  accessModes: ["ReadWriteOnce"]
  persistentVolumeReclaimPolicy: Retain
  storageClassName: local-storage
  local:
    path: /mnt/nvme0
  nodeAffinity:
    required:
      nodeSelectorTerms:
        - matchExpressions:
            - key: kubernetes.io/hostname
              operator: In
              values: ["$NODE"]
PV_EOF"#, size = answers.storage.size));
        s.cmd("  echo \"Created PV kafka-nvme-$INDEX on $NODE\"");
        s.cmd("  INDEX=$((INDEX + 1))");
        s.cmd("done");
        s.blank();

        s.comment("NVMe format DaemonSet left running to maintain mount propagation");
    } else {
        let is_provisioned = answers.storage.performance.as_deref() == Some("provisioned");
        let (sc_name, extra_params) = if is_provisioned {
            let iops = answers.storage.iops.unwrap_or(16000);
            let throughput = answers.storage.throughput_mbs.unwrap_or(1000);
            ("gp3-fast", format!("  iops: \"{}\"\n  throughput: \"{}\"", iops, throughput))
        } else {
            ("gp3", String::new())
        };

        // Tag every dynamically-provisioned EBS volume with the cluster + dimster
        // name so teardown can safely identify and sweep orphans without risking
        // unrelated volumes in the same AWS account.
        let tag_params = format!(
            "  tagSpecification_1: \"dimster-cluster={}\"\n  tagSpecification_2: \"dimster-name={}\"",
            cluster_name, name
        );

        let mut sc = format!(
            "apiVersion: storage.k8s.io/v1\nkind: StorageClass\nmetadata:\n  name: {}\nprovisioner: ebs.csi.aws.com\nparameters:\n  type: gp3\n  fsType: xfs",
            sc_name
        );
        if !extra_params.is_empty() {
            sc.push('\n');
            sc.push_str(&extra_params);
        }
        sc.push('\n');
        sc.push_str(&tag_params);
        // Explicit reclaimPolicy: Delete — already the default for dynamic
        // provisioning, but stating it makes intent unambiguous.
        sc.push_str("\nreclaimPolicy: Delete\nvolumeBindingMode: WaitForFirstConsumer\nallowVolumeExpansion: true");
        s.heredoc("kubectl apply -f -", &sc);
    }

    // Step 5: Generate config files
    s.section("Step 5: Generate Configuration Files");

    let env_name = &answers.env_name;

    let config = if answers.is_external() {
        let bootstrap = answers.bootstrap_servers.as_deref().unwrap_or("CHANGE_ME:9092");
        format!(
            r#"# Dimster configuration — generated by eks-setup for '{name}' (external)
kubernetes:
  namespace: dimster

# No `image:` block: the dimster CLI defaults the tag to its own version,
# so generated configs stay aligned with whichever CLI binary you run.
# Every `dimster build` also produces a :latest-kafka<kver> alias, so
# `tag: latest` is a valid alternative if you prefer not to pin. Override
# only if you need a custom image tag:
#   image:
#     tag: 0.1.0       # pin to a specific version
#     # tag: latest    # always resolve to the most recently built image

environments:
  local:
    image: dimster
  {env_name}:
    image: ${{AWS_ACCOUNT_ID}}.dkr.ecr.${{AWS_REGION}}.amazonaws.com/${{DIMSTER_NAME}}
    context: $(kubectl config current-context)
    deploy: external
    connection:
      bootstrap.servers: "{bootstrap}"
    workers:
      replicas: {worker_count}
      heap: "{worker_heap}"
      requests:
        cpu: "{worker_cpu}"
        memory: "{worker_memory}"
      nodeLabel: "role=worker"
    coordinator:
      heap: "{coord_heap}"
      requests:
        cpu: "{coord_cpu}"
        memory: "{coord_memory}"
    monitoring:
      nodeLabel: "role=infra"
      prometheus:
        requests:
          cpu: "{prom_cpu}"
          memory: "{prom_memory}"
      grafana:
        requests:
          cpu: "{grafana_cpu}"
          memory: "{grafana_memory}"

results:
  dir: ./results"#,
            name = name,
            env_name = env_name,
            bootstrap = bootstrap,
            worker_count = answers.workers.count,
            worker_heap = answers.workers.heap,
            worker_cpu = answers.workers.cpu,
            worker_memory = answers.workers.memory,
            coord_heap = answers.coordinator.heap,
            coord_cpu = answers.coordinator.cpu,
            coord_memory = answers.coordinator.memory,
            prom_cpu = answers.monitoring.prometheus_cpu,
            prom_memory = answers.monitoring.prometheus_memory,
            grafana_cpu = answers.monitoring.grafana_cpu,
            grafana_memory = answers.monitoring.grafana_memory,
        )
    } else {
        let storage_class = if answers.storage.storage_type == "instance-store" {
            "local-storage"
        } else if answers.storage.performance.as_deref() == Some("provisioned") {
            "gp3-fast"
        } else {
            "gp3"
        };

        format!(
            r#"# Dimster configuration — generated by eks-setup for '{name}'
kubernetes:
  namespace: dimster

# No `image:` block: the dimster CLI defaults the tag to its own version,
# so generated configs stay aligned with whichever CLI binary you run.
# Every `dimster build` also produces a :latest-kafka<kver> alias, so
# `tag: latest` is a valid alternative if you prefer not to pin. Override
# only if you need a custom image tag:
#   image:
#     tag: 0.1.0       # pin to a specific version
#     # tag: latest    # always resolve to the most recently built image

environments:
  local:
    image: dimster
  {env_name}:
    image: ${{AWS_ACCOUNT_ID}}.dkr.ecr.${{AWS_REGION}}.amazonaws.com/${{DIMSTER_NAME}}
    context: $(kubectl config current-context)
    deploy: full
    kafka:
      replicas: {kafka_count}
      version: "{kafka_version}"
      pvcSize: {kafka_storage}
      pvcStorageClass: {storage_class}
      heap: "{kafka_heap}"
      requests:
        cpu: "{kafka_cpu}"
        memory: "{kafka_memory}"
      nodeLabel: "role=kafka"
    workers:
      replicas: {worker_count}
      heap: "{worker_heap}"
      requests:
        cpu: "{worker_cpu}"
        memory: "{worker_memory}"
      nodeLabel: "role=worker"
    coordinator:
      heap: "{coord_heap}"
      requests:
        cpu: "{coord_cpu}"
        memory: "{coord_memory}"
    monitoring:
      nodeLabel: "role=infra"
      prometheus:
        requests:
          cpu: "{prom_cpu}"
          memory: "{prom_memory}"
      grafana:
        requests:
          cpu: "{grafana_cpu}"
          memory: "{grafana_memory}"

results:
  dir: ./results"#,
            name = name,
            env_name = env_name,
            kafka_version = answers.kafka.version,
            kafka_count = answers.kafka.count,
            kafka_storage = answers.storage.size,
            storage_class = storage_class,
            kafka_heap = answers.kafka.heap,
            kafka_cpu = answers.kafka.cpu,
            kafka_memory = answers.kafka.memory,
            worker_count = answers.workers.count,
            worker_heap = answers.workers.heap,
            worker_cpu = answers.workers.cpu,
            worker_memory = answers.workers.memory,
            coord_heap = answers.coordinator.heap,
            coord_cpu = answers.coordinator.cpu,
            coord_memory = answers.coordinator.memory,
            prom_cpu = answers.monitoring.prometheus_cpu,
            prom_memory = answers.monitoring.prometheus_memory,
            grafana_cpu = answers.monitoring.grafana_cpu,
            grafana_memory = answers.monitoring.grafana_memory,
        )
    };

    let config_path = format!("dimster-config-{}.yaml", name);
    s.cmd(&format!("cat > \"{}\" <<'CONFIG_EOF'", config_path));
    for line in config.lines() {
        s.cmd(line);
    }
    s.cmd("CONFIG_EOF");
    s.cmd(&format!("echo \"Wrote {}\"", config_path));
    s.blank();
    s.cmd("echo \"\"");
    s.cmd("echo \"Done! Next steps:\"");
    s.cmd(&format!("echo \"  1. Review {}\"", config_path));
    s.cmd(&format!("echo \"  2. Copy: cp {} dimster-config.yaml\"", config_path));
    s.cmd("echo \"  3. Log in to ECR (token expires every 12 hours):\"");
    s.cmd(&format!("echo \"     aws ecr get-login-password --region $AWS_REGION | \\\\\""));
    s.cmd(&format!("echo \"       docker login --username AWS --password-stdin ${{AWS_ACCOUNT_ID}}.dkr.ecr.${{AWS_REGION}}.amazonaws.com\""));
    s.cmd(&format!("echo \"  4. Build and push: ./dimster build {}\"", env_name));
    s.cmd(&format!("echo \"  5. Deploy: ./dimster deploy {}\"", env_name));
    s.blank();

    Ok(s.render())
}

