/// Insert or replace an environment in an existing dimster-config.yaml.
fn insert_env_into_config(
    config_path: &str,
    env_name: &str,
    env_value: serde_yaml::Value,
) -> Result<()> {
    use serde_yaml::{Mapping, Value};

    let content = std::fs::read_to_string(config_path)?;
    let mut doc: Value = serde_yaml::from_str(&content)?;

    // Ensure environments mapping exists
    let environments = doc
        .as_mapping_mut()
        .ok_or_else(|| anyhow::anyhow!("dimster-config.yaml is not a YAML mapping"))?
        .entry(Value::String("environments".into()))
        .or_insert_with(|| Value::Mapping(Mapping::new()));

    let envs_map = environments
        .as_mapping_mut()
        .ok_or_else(|| anyhow::anyhow!("'environments' is not a YAML mapping"))?;

    envs_map.insert(Value::String(env_name.into()), env_value);

    let output = serde_yaml::to_string(&doc)?;
    std::fs::write(config_path, output)?;

    Ok(())
}

