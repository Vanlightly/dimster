fn step_1_ecr(answers: &Answers, mode: Mode) -> Result<()> {
    println!("\n=== Step 1/5: Create ECR Repository ===\n");

    if mode == Mode::DryRun {
        println!("  [dry-run] aws ecr create-repository --repository-name {} --region {}", answers.aws.dimster_name, answers.aws.region);
        return Ok(());
    }

    // Check if already exists
    let check = Command::new("aws")
        .args(["ecr", "describe-repositories", "--repository-names", &answers.aws.dimster_name, "--region", &answers.aws.region])
        .output()?;

    if check.status.success() {
        println!("  ✓ ECR repository already exists");
        return Ok(());
    }

    confirm_and_run(
        "aws",
        &["ecr", "create-repository", "--repository-name", &answers.aws.dimster_name, "--region", &answers.aws.region],
    )?;
    println!("  ✓ ECR repository created");
    Ok(())
}

fn step_2_eks(answers: &Answers, mode: Mode) -> Result<()> {
    println!("\n=== Step 2/5: Create EKS Cluster ===\n");

    let cluster_name = format!("{}-benchmark", answers.aws.dimster_name);

    // eksctl needs at least 2 AZs for VPC subnets; pick a second one different from the desired AZ
    let az = &answers.aws.az;
    let second_az = {
        let suffix = az.chars().last().unwrap_or('a');
        let other = if suffix == 'a' { 'b' } else { 'a' };
        format!("{}{}", &az[..az.len() - 1], other)
    };

    let kafka_node_group = if answers.is_external() {
        String::new()
    } else {
        format!(
            r#"  - name: kafka
    instanceType: {kafka_type}
    desiredCapacity: {kafka_count}
    minSize: {kafka_count}
    maxSize: {kafka_count}
    availabilityZones: ["{az}"]
    labels:
      role: kafka

"#,
            kafka_type = answers.kafka.instance_type,
            kafka_count = answers.kafka.count,
            az = az,
        )
    };

    let eksctl_config = format!(
        r#"apiVersion: eksctl.io/v1alpha5
kind: ClusterConfig

metadata:
  name: {cluster_name}
  region: {region}
  version: "{eks_version}"

availabilityZones: ["{az}", "{second_az}"]

managedNodeGroups:
{kafka_node_group}  - name: workers
    instanceType: {worker_type}
    desiredCapacity: {worker_count}
    minSize: {worker_min}
    maxSize: {worker_max}
    availabilityZones: ["{az}"]
    labels:
      role: worker

  - name: infra
    instanceType: {infra_type}
    desiredCapacity: 1
    minSize: 1
    maxSize: 1
    availabilityZones: ["{az}"]
    labels:
      role: infra
"#,
        cluster_name = cluster_name,
        region = answers.aws.region,
        eks_version = answers.aws.eks_version,
        kafka_node_group = kafka_node_group,
        az = az,
        second_az = second_az,
        worker_type = answers.workers.instance_type,
        worker_count = answers.workers.count,
        worker_min = answers.workers.min,
        worker_max = answers.workers.max,
        infra_type = answers.coordinator.infra_instance_type,
    );

    let config_path = format!("/tmp/eks-cluster-{}.yaml", answers.aws.dimster_name);

    if mode == Mode::DryRun {
        println!("  [dry-run] Would write eksctl config to {}", config_path);
        println!("  [dry-run] eksctl create cluster -f {}", config_path);
        println!("\n  eksctl config:\n");
        for line in eksctl_config.lines() {
            println!("    {}", line);
        }
        return Ok(());
    }

    // Check if cluster already exists
    let check = Command::new("eksctl")
        .args(["get", "cluster", "--name", &cluster_name, "--region", &answers.aws.region])
        .output()?;

    if check.status.success() {
        println!("  ✓ EKS cluster '{}' already exists", cluster_name);
        println!("  Updating kubeconfig...");
        let update = Command::new("aws")
            .args(["eks", "update-kubeconfig",
                   "--name", &cluster_name,
                   "--region", &answers.aws.region])
            .output()?;
        if !update.status.success() {
            let stderr = String::from_utf8_lossy(&update.stderr);
            bail!("Failed to update kubeconfig: {}", stderr);
        }
        println!("  ✓ Kubeconfig updated");

        // Check for missing node groups and create them
        ensure_node_groups(answers, &cluster_name, &config_path, &eksctl_config)?;

        verify_nodes()?;
        return Ok(());
    }

    std::fs::write(&config_path, &eksctl_config)?;
    println!("  Wrote eksctl config to {}", config_path);

    confirm_and_run_inherit(
        "eksctl",
        &["create", "cluster", "-f", &config_path],
    )?;

    println!("  ✓ EKS cluster created");
    verify_nodes()?;
    Ok(())
}

