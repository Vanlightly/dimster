pub fn delete_all(dimster_name: &str, region: &str, keep_ecr: bool, mode: Mode) -> Result<()> {
    if mode == Mode::GenerateScript {
        let script = generate_delete_script(dimster_name, region, keep_ecr)?;
        print!("{}", script);
        return Ok(());
    }

    let cluster_name = format!("{}-benchmark", dimster_name);

    // Step 1: Graceful PVC deletion. Deleting PVCs while the cluster is still
    // healthy lets the EBS CSI driver call DeleteVolume on AWS for each PV.
    // Without this, `eksctl delete cluster` nukes the cluster before the CSI
    // driver can free the volumes — orphaning them as `available` in EC2.
    // Best-effort only: if kubectl can't reach the cluster, we skip and rely
    // on the post-delete sweep (Step 3) as a safety net.
    println!("\n=== Step 1/4: Delete PVCs (graceful) ===\n");
    delete_cluster_pvcs(&cluster_name, region, mode)?;

    // Step 2: Delete EKS cluster
    println!("\n=== Step 2/4: Delete EKS Cluster ===\n");

    if mode == Mode::DryRun {
        println!("  [dry-run] eksctl delete cluster --name {} --region {}", cluster_name, region);
    } else {
        // Check if cluster exists
        let check = Command::new("eksctl")
            .args(["get", "cluster", "--name", &cluster_name, "--region", region])
            .output()?;

        if !check.status.success() {
            println!("  ✓ EKS cluster '{}' does not exist (already deleted)", cluster_name);
        } else {
            confirm_and_run_inherit(
                "eksctl",
                &["delete", "cluster", "--name", &cluster_name, "--region", region],
            )?;
            println!("  ✓ EKS cluster '{}' deleted", cluster_name);
        }
    }

    // Step 3: Safety net — sweep any EBS volumes still tagged with this
    // cluster. Catches the cases where Step 1 was skipped (cluster
    // unreachable), PVC deletion timed out, or volumes were created outside
    // the dimster namespaces.
    println!("\n=== Step 3/4: Sweep Orphaned EBS Volumes ===\n");
    sweep_orphaned_volumes(&cluster_name, region, mode)?;

    // Step 4: Delete ECR repository
    println!("\n=== Step 4/4: Delete ECR Repository ===\n");

    if keep_ecr {
        println!("  Skipped (--keep-ecr)");
    } else if mode == Mode::DryRun {
        println!("  [dry-run] aws ecr delete-repository --repository-name {} --region {} --force", dimster_name, region);
    } else {
        let check = Command::new("aws")
            .args(["ecr", "describe-repositories", "--repository-names", dimster_name, "--region", region])
            .output()?;

        if !check.status.success() {
            println!("  ✓ ECR repository '{}' does not exist (already deleted)", dimster_name);
        } else {
            confirm_and_run(
                "aws",
                &["ecr", "delete-repository", "--repository-name", dimster_name, "--region", region, "--force"],
            )?;
            println!("  ✓ ECR repository '{}' deleted", dimster_name);
        }
    }

    println!("\n=== Done! ===\n");
    println!("  Note: Generated config files (dimster-config-{}.yaml, eks-answers-{}.yaml)", dimster_name, dimster_name);
    println!("  were left on disk. Delete them manually if no longer needed.");

    Ok(())
}

/// Delete all PVCs across all namespaces so the EBS CSI driver can free the
/// underlying volumes on AWS before the cluster is destroyed. Best-effort:
/// returns Ok even when the cluster is unreachable or the delete times out —
/// the orphan sweep in Step 3 is the authoritative cleanup.
fn delete_cluster_pvcs(cluster_name: &str, region: &str, mode: Mode) -> Result<()> {
    if mode == Mode::DryRun {
        println!("  [dry-run] kubectl delete pvc --all --all-namespaces --wait=true --timeout=120s");
        println!("            (against cluster '{}' in {})", cluster_name, region);
        return Ok(());
    }

    // Probe kubectl reachability quietly. If kubeconfig has no context for this
    // cluster (e.g., already deleted, never joined), skip without erroring.
    let probe = Command::new("kubectl")
        .args(["get", "ns", "--request-timeout=10s"])
        .output();

    match probe {
        Ok(out) if out.status.success() => {}
        _ => {
            println!("  ✓ kubectl cannot reach cluster — skipping graceful PVC delete");
            println!("    (orphaned volumes will be cleaned in Step 3)");
            return Ok(());
        }
    }

    println!("  → kubectl delete pvc --all --all-namespaces --wait=true --timeout=120s");
    let status = Command::new("kubectl")
        .args(["delete", "pvc", "--all", "--all-namespaces", "--wait=true", "--timeout=120s"])
        .stdout(std::process::Stdio::inherit())
        .stderr(std::process::Stdio::inherit())
        .status();

    match status {
        Ok(s) if s.success() => println!("  ✓ PVCs deleted; CSI driver will release EBS volumes"),
        _ => println!("  ⚠ PVC delete did not complete cleanly — Step 3 will sweep remaining volumes"),
    }
    Ok(())
}

/// Find EBS volumes tagged with this cluster that remain in `available`
/// state, and delete them. The `dimster-cluster` tag is set on every volume
/// dynamically provisioned by our StorageClass (see setup_ebs_storage), so
/// matches are always cluster-scoped — never volumes from unrelated workloads.
fn sweep_orphaned_volumes(cluster_name: &str, region: &str, mode: Mode) -> Result<()> {
    if mode == Mode::DryRun {
        println!(
            "  [dry-run] aws ec2 describe-volumes --region {} \\",
            region
        );
        println!("              --filters Name=tag:dimster-cluster,Values={} \\", cluster_name);
        println!("                        Name=status,Values=available");
        println!("  [dry-run] for each volume: aws ec2 delete-volume --volume-id <id>");
        return Ok(());
    }

    let output = Command::new("aws")
        .args([
            "ec2", "describe-volumes",
            "--region", region,
            "--filters",
            &format!("Name=tag:dimster-cluster,Values={}", cluster_name),
            "Name=status,Values=available",
            "--query", "Volumes[].VolumeId",
            "--output", "text",
        ])
        .output()?;

    if !output.status.success() {
        let stderr = String::from_utf8_lossy(&output.stderr);
        bail!("aws ec2 describe-volumes failed: {}", stderr);
    }

    let raw = String::from_utf8_lossy(&output.stdout);
    let volume_ids: Vec<&str> = raw.split_whitespace().collect();

    if volume_ids.is_empty() {
        println!("  ✓ No orphaned EBS volumes found for cluster '{}'", cluster_name);
        return Ok(());
    }

    println!("  Found {} orphaned EBS volume(s) tagged dimster-cluster={}:", volume_ids.len(), cluster_name);
    for id in &volume_ids {
        println!("    - {}", id);
    }

    for id in &volume_ids {
        confirm_and_run(
            "aws",
            &["ec2", "delete-volume", "--region", region, "--volume-id", id],
        )?;
        println!("  ✓ Deleted volume {}", id);
    }
    Ok(())
}

fn generate_delete_script(dimster_name: &str, region: &str, keep_ecr: bool) -> Result<String> {
    let mut s = Script::new();
    let cluster_name = format!("{}-benchmark", dimster_name);

    s.cmd("#!/usr/bin/env bash");
    s.cmd("set -euo pipefail");
    s.blank();
    s.comment(&format!("EKS teardown script for '{}'", dimster_name));
    s.comment("Generated by eks-setup. Review before running.");

    s.section("Variables");
    s.cmd(&format!("DIMSTER_NAME=\"{}\"", dimster_name));
    s.cmd(&format!("AWS_REGION=\"{}\"", region));
    s.cmd(&format!("CLUSTER_NAME=\"{}\"", cluster_name));

    // Step 1: Best-effort PVC delete so the EBS CSI driver releases volumes
    // on AWS before the cluster is destroyed. Failures here are non-fatal —
    // the volume sweep in Step 3 picks up anything left behind.
    s.section("Step 1: Delete PVCs (graceful)");
    s.cmd("if kubectl get ns --request-timeout=10s &>/dev/null; then");
    s.cmd("  echo \"Deleting all PVCs so the EBS CSI driver can free volumes...\"");
    s.cmd("  kubectl delete pvc --all --all-namespaces --wait=true --timeout=120s || \\");
    s.cmd("    echo \"PVC delete did not complete cleanly — Step 3 will sweep remaining volumes\"");
    s.cmd("else");
    s.cmd("  echo \"kubectl cannot reach cluster — skipping graceful PVC delete\"");
    s.cmd("fi");

    s.section("Step 2: Delete EKS Cluster");
    s.cmd(&format!(
        "if eksctl get cluster --name \"$CLUSTER_NAME\" --region \"$AWS_REGION\" &>/dev/null; then"
    ));
    s.cmd("  echo \"Deleting EKS cluster $CLUSTER_NAME (this takes 10-15 minutes)...\"");
    s.cmd("  eksctl delete cluster --name \"$CLUSTER_NAME\" --region \"$AWS_REGION\"");
    s.cmd("  echo \"EKS cluster deleted\"");
    s.cmd("else");
    s.cmd("  echo \"EKS cluster $CLUSTER_NAME does not exist\"");
    s.cmd("fi");

    // Step 3: Sweep any EBS volumes still tagged with this cluster. Tag is
    // applied at provision time by the StorageClass, so matches are
    // cluster-scoped and safe to delete.
    s.section("Step 3: Sweep Orphaned EBS Volumes");
    s.cmd("ORPHANED_VOLUMES=$(aws ec2 describe-volumes --region \"$AWS_REGION\" \\");
    s.cmd("  --filters \"Name=tag:dimster-cluster,Values=$CLUSTER_NAME\" \\");
    s.cmd("            \"Name=status,Values=available\" \\");
    s.cmd("  --query 'Volumes[].VolumeId' --output text)");
    s.cmd("if [ -z \"$ORPHANED_VOLUMES\" ]; then");
    s.cmd("  echo \"No orphaned EBS volumes found for $CLUSTER_NAME\"");
    s.cmd("else");
    s.cmd("  echo \"Deleting orphaned EBS volumes: $ORPHANED_VOLUMES\"");
    s.cmd("  for VOL in $ORPHANED_VOLUMES; do");
    s.cmd("    aws ec2 delete-volume --region \"$AWS_REGION\" --volume-id \"$VOL\"");
    s.cmd("    echo \"Deleted $VOL\"");
    s.cmd("  done");
    s.cmd("fi");

    if keep_ecr {
        s.section("Step 4: Delete ECR Repository — skipped (--keep-ecr)");
    } else {
        s.section("Step 4: Delete ECR Repository");
        s.cmd(&format!(
            "if aws ecr describe-repositories --repository-names \"$DIMSTER_NAME\" --region \"$AWS_REGION\" &>/dev/null; then"
        ));
        s.cmd("  echo \"Deleting ECR repository $DIMSTER_NAME...\"");
        s.cmd("  aws ecr delete-repository --repository-name \"$DIMSTER_NAME\" --region \"$AWS_REGION\" --force");
        s.cmd("  echo \"ECR repository deleted\"");
        s.cmd("else");
        s.cmd("  echo \"ECR repository $DIMSTER_NAME does not exist\"");
        s.cmd("fi");
    }

    s.blank();
    s.cmd("echo \"\"");
    s.cmd("echo \"Done! Cluster and resources have been deleted.\"");
    s.cmd(&format!("echo \"Note: Config files (dimster-config-{}.yaml, eks-answers-{}.yaml) left on disk.\"", dimster_name, dimster_name));
    s.blank();

    Ok(s.render())
}

